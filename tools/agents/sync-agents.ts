// Generates the Claude Code adapters from the single source in .agents/ and validates it.
//
//   npm run agents          # regenerate adapters
//   npm run agents:check    # validate + fail if adapters are stale (CI)
//
// Source of truth (edit these):
//   .agents/rules/*.md        constitution & guardrails (frontmatter: trigger, description)
//   .agents/agents/*.md       agent roles (frontmatter: name, description, tools, skills)
//   .agents/skills/rj-*/      team skills (SKILL.md with name + description)
// Generated (never edit by hand; every file carries a GENERATED marker):
//   .agents/workflows/rj-*.md  Antigravity slash workflows -> skills
//   .claude/skills/rj-*/       Claude Code skill copies
//   .claude/agents/rj-*.md     Claude Code subagents
// Codex, Cursor and Antigravity read AGENTS.md and .agents/ directly (ADR-0014).
// OpenSpec skills (openspec-*) are managed by `openspec init/update` and only validated here.
import { existsSync, readdirSync, readFileSync, rmSync, statSync, unlinkSync } from 'node:fs';
import { dirname } from 'node:path';
import { parseArgs } from 'node:util';
import { readText, rel, repoPath, run, syncOutputs } from '../lib.ts';

const AGENTS_DIR = repoPath('.agents');
const SKILL_TARGET = repoPath('.claude/skills');
const TEAM_PREFIX = 'rj-';
const NAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const GENERATED = 'GENERATED by tools/agents/sync-agents.ts';
const marker = (source: string) => `<!-- ${GENERATED} from ${source} - edit the source, not this file. -->`;

// Canonical tool ids (Antigravity ids and logical categories) -> Claude Code tool names.
const CLAUDE_TOOLS: Record<string, string[]> = {
  read: ['Read', 'Glob'], edit: ['Write', 'Edit'], search: ['Grep', 'Glob'], execute: ['Bash'], todo: [], agent: ['Task'],
  view_file: ['Read'], list_dir: ['Glob'], find_by_name: ['Glob'], grep_search: ['Grep'], run_command: ['Bash'],
  write_to_file: ['Write', 'Edit'], replace_file_content: ['Edit'], multi_replace_file_content: ['Edit'],
  search_web: ['WebSearch'], read_url_content: ['WebFetch'], invoke_subagent: ['Task'], send_message: [],
};
const RULE_TRIGGERS = new Set(['always_on', 'model_decision', 'glob', 'manual']);

interface Doc {
  path: string;
  meta: Record<string, string | string[]>;
  body: string;
}

const unquote = (v: string) => (v.length >= 2 && v[0] === v.at(-1) && `"'`.includes(v[0]) ? v.slice(1, -1) : v);
const yamlStr = (v: string) => `"${v.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
const withMarker = (front: string, source: string, body: string) => `---\n${front}---\n\n${marker(rel(source))}\n\n${body.trimEnd()}\n`;

function parseFrontmatter(path: string): Doc {
  const text = readText(path);
  if (!text.startsWith('---\n')) throw new Error(`${rel(path)}: must start with '---' frontmatter`);
  const end = text.indexOf('\n---\n', 4);
  if (end === -1) throw new Error(`${rel(path)}: unterminated frontmatter`);
  const meta: Doc['meta'] = {};
  let list: string[] | null = null;
  for (const raw of text.slice(4, end).split('\n')) {
    if (!raw.trim() || raw.trimStart().startsWith('#')) continue;
    if (raw.startsWith('  - ') || raw.startsWith('- ')) {
      if (!list) throw new Error(`${rel(path)}: list item without key: '${raw}'`);
      list.push(unquote(raw.split('- ').slice(1).join('- ').split(' #')[0].trim()));
      continue;
    }
    const colon = raw.indexOf(':');
    if (colon === -1) throw new Error(`${rel(path)}: cannot parse frontmatter line '${raw}'`);
    const key = raw.slice(0, colon).trim();
    const value = raw.slice(colon + 1).split(' #')[0].trim();
    if (value === '') meta[key] = list = [];
    else {
      list = null;
      meta[key] = unquote(value);
    }
  }
  return { path, meta, body: text.slice(end + 5).replace(/^\n+/, '') };
}

const listDirs = (dir: string) => (existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : []);
const listFiles = (dir: string, ext: string) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : []);
const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(`${dir}/${d.name}`) : [`${dir}/${d.name}`])).sort();

function validate() {
  const errors: string[] = [];
  const parse = (path: string): Doc | null => {
    try {
      return parseFrontmatter(path);
    } catch (e) {
      errors.push((e as Error).message);
      return null;
    }
  };

  const skills: Doc[] = [];
  for (const folder of listDirs(`${AGENTS_DIR}/skills`)) {
    const path = `${AGENTS_DIR}/skills/${folder}/SKILL.md`;
    if (!existsSync(path)) continue;
    const doc = parse(path);
    if (!doc) continue;
    const name = String(doc.meta.name ?? '');
    const description = String(doc.meta.description ?? '');
    if (!NAME_RE.test(name)) errors.push(`${rel(path)}: invalid name '${name}'`);
    if (name !== folder) errors.push(`${rel(path)}: name '${name}' must equal folder '${folder}'`);
    if (!description || description.length > 1024) errors.push(`${rel(path)}: description must be 1..1024 characters`);
    skills.push(doc);
  }
  const names = skills.map((s) => String(s.meta.name));
  for (const n of [...new Set(names.filter((n, i) => names.indexOf(n) !== i))].sort()) errors.push(`duplicate skill name '${n}'`);

  const agents: Doc[] = [];
  for (const file of listFiles(`${AGENTS_DIR}/agents`, '.md')) {
    const path = `${AGENTS_DIR}/agents/${file}`;
    const doc = parse(path);
    if (!doc) continue;
    const name = String(doc.meta.name ?? '');
    if (name !== file.slice(0, -3) || !NAME_RE.test(name)) errors.push(`${rel(path)}: name '${name}' must equal file name and be kebab-case`);
    if (!doc.meta.description) errors.push(`${rel(path)}: missing description`);
    const tools = doc.meta.tools;
    if (!Array.isArray(tools) || tools.length === 0) errors.push(`${rel(path)}: tools must be a non-empty list`);
    else for (const t of tools) if (!(t in CLAUDE_TOOLS)) errors.push(`${rel(path)}: unknown tool '${t}'`);
    const agentSkills = doc.meta.skills;
    if (!Array.isArray(agentSkills) || agentSkills.length === 0) errors.push(`${rel(path)}: skills must be a non-empty list of built-in skills`);
    else for (const s of agentSkills) if (!names.includes(s)) errors.push(`${rel(path)}: references unknown skill '${s}'`);
    agents.push(doc);
  }

  const rules: Doc[] = [];
  for (const file of listFiles(`${AGENTS_DIR}/rules`, '.md')) {
    const path = `${AGENTS_DIR}/rules/${file}`;
    const doc = parse(path);
    if (!doc) continue;
    if (!RULE_TRIGGERS.has(String(doc.meta.trigger))) errors.push(`${rel(path)}: trigger must be one of [${[...RULE_TRIGGERS].sort().join(', ')}]`);
    if (!doc.meta.description) errors.push(`${rel(path)}: missing description`);
    rules.push(doc);
  }
  return { errors, skills, agents, rules };
}

function expectedFiles(skills: Doc[], agents: Doc[]): Map<string, string | Buffer> {
  const out = new Map<string, string | Buffer>();
  for (const skill of skills) {
    const folder = dirname(skill.path);
    const name = folder.split('/').at(-1)!;
    if (!name.startsWith(TEAM_PREFIX)) continue;
    const front = `name: ${name}\ndescription: ${yamlStr(String(skill.meta.description))}\n`;
    for (const src of walk(folder)) {
      const dest = `${SKILL_TARGET}/${name}${src.slice(folder.length)}`;
      out.set(dest, src === skill.path ? withMarker(front, skill.path, skill.body) : readFileSync(src));
    }
    out.set(
      `${AGENTS_DIR}/workflows/${name}.md`,
      `---\ndescription: ${yamlStr(String(skill.meta.description))}\n---\n\n${marker(rel(skill.path))}\n\nFollow the skill \`${rel(skill.path)}\` step by step. Read it fully before acting.\n`,
    );
  }
  for (const agent of agents) {
    const tools: string[] = [];
    for (const tool of agent.meta.tools as string[]) for (const t of CLAUDE_TOOLS[tool]) if (!tools.includes(t)) tools.push(t);
    const front = `name: ${agent.meta.name}\ndescription: ${yamlStr(String(agent.meta.description))}\ntools: ${tools.join(', ')}\n`;
    out.set(repoPath(`.claude/agents/${agent.meta.name}.md`), withMarker(front, agent.path, agent.body));
  }
  return out;
}

/** Files produced earlier by this generator (they carry the marker) — used to remove orphans. */
function generatedOnDisk(): string[] {
  const candidates = [
    ...listFiles(`${AGENTS_DIR}/workflows`, '.md').filter((f) => f.startsWith(TEAM_PREFIX)).map((f) => `${AGENTS_DIR}/workflows/${f}`),
    ...listFiles(repoPath('.claude/agents'), '.md').map((f) => repoPath(`.claude/agents/${f}`)),
    ...listDirs(SKILL_TARGET).filter((d) => d.startsWith(TEAM_PREFIX)).flatMap((d) => walk(`${SKILL_TARGET}/${d}`)),
  ];
  return candidates.filter((p) => !p.endsWith('.md') || /GENERATED by tools\/agents\/sync[-_]agents/.test(readFileSync(p, 'utf8')));
}

run(() => {
  const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
  const { errors, skills, agents, rules } = validate();
  if (errors.length) {
    console.log('Validation errors:');
    for (const e of errors) console.log(`  - ${e}`);
    return 1;
  }

  const expected = expectedFiles(skills, agents);
  const orphans = generatedOnDisk().filter((p) => !expected.has(p));
  const stale = syncOutputs(expected, values.check);

  if (values.check) {
    for (const p of stale) console.log(`stale: ${rel(p)}`);
    for (const p of orphans) console.log(`orphan: ${rel(p)} (source removed)`);
    if (stale.length || orphans.length) {
      console.log('Run: npm run agents');
      return 1;
    }
    console.log(`OK: ${skills.length} skills, ${agents.length} agents, ${rules.length} rules; ${expected.size} generated files up to date`);
    return 0;
  }

  for (const p of orphans) {
    unlinkSync(p);
    const parent = dirname(p);
    if (existsSync(parent) && statSync(parent).isDirectory() && readdirSync(parent).length === 0) rmSync(parent, { recursive: true, force: true });
  }
  console.log(`Generated ${stale.length} file(s), removed ${orphans.length} orphan(s); ${expected.size} adapters total`);
  return 0;
});
