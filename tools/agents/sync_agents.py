"""Generate tool-specific agent files from the single source in .agents/ and validate them.

Usage:
    python tools/agents/sync_agents.py          # regenerate adapters
    python tools/agents/sync_agents.py --check  # validate + fail if adapters are stale (CI)

Source of truth (edit these):
    .agents/rules/*.md          Antigravity rules (frontmatter: trigger, description)
    .agents/agents/*.md         agent roles (Antigravity custom-agent frontmatter)
    .agents/skills/rj-*/        team skills (SKILL.md with name + description)

Generated (never edit by hand; every file carries a GENERATED marker):
    .agents/workflows/rj-*.md                  Antigravity slash workflows -> skills
    .claude/skills/rj-*/  .github/skills/rj-*/  .gemini/skills/rj-*/   skill copies
    .claude/agents/rj-*.md                     Claude Code subagents
    .github/agents/rj-*.agent.md               GitHub Copilot custom agents
    .github/instructions/*.instructions.md     Copilot instructions from rules

OpenSpec skills (openspec-*) are managed by `openspec init/update` and only validated here.
Standard library only, so it runs anywhere Python 3.11+ is installed.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AGENTS_DIR = ROOT / ".agents"
SKILL_TARGETS = [ROOT / ".claude" / "skills", ROOT / ".github" / "skills", ROOT / ".gemini" / "skills"]
TEAM_PREFIX = "rj-"
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
MARKER = "<!-- GENERATED by tools/agents/sync_agents.py from {source} - edit the source, not this file. -->"

# Antigravity tool ids -> Claude Code tool names
CLAUDE_TOOLS = {
    "view_file": ["Read"],
    "list_dir": ["Glob"],
    "find_by_name": ["Glob"],
    "grep_search": ["Grep"],
    "run_command": ["Bash"],
    "write_to_file": ["Write", "Edit"],
    "replace_file_content": ["Edit"],
    "multi_replace_file_content": ["Edit"],
    "search_web": ["WebSearch"],
    "read_url_content": ["WebFetch"],
    "invoke_subagent": ["Task"],
    "send_message": [],
}
RULE_TRIGGERS = {"always_on", "model_decision", "glob", "manual"}


@dataclass
class Doc:
    path: Path
    meta: dict[str, object]
    body: str


def parse_frontmatter(path: Path) -> Doc:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{rel(path)}: must start with '---' frontmatter")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError(f"{rel(path)}: unterminated frontmatter")
    meta: dict[str, object] = {}
    current_list: list[str] | None = None
    for raw in text[4:end].splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.startswith("  - ") or raw.startswith("- "):
            if current_list is None:
                raise ValueError(f"{rel(path)}: list item without key: {raw!r}")
            current_list.append(unquote(raw.split("- ", 1)[1].split(" #", 1)[0].strip()))
            continue
        key, sep, value = raw.partition(":")
        if not sep:
            raise ValueError(f"{rel(path)}: cannot parse frontmatter line {raw!r}")
        value = value.split(" #", 1)[0].strip()
        if value == "":
            current_list = []
            meta[key.strip()] = current_list
        else:
            current_list = None
            meta[key.strip()] = unquote(value)
    return Doc(path, meta, text[end + 5 :].lstrip("\n"))


def unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def yaml_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def with_marker(frontmatter: str, source: Path, body: str) -> str:
    return f"---\n{frontmatter}---\n\n{MARKER.format(source=rel(source))}\n\n{body.rstrip()}\n"


# ---------------------------------------------------------------- validation


def validate() -> tuple[list[str], list[Doc], list[Doc], list[Doc]]:
    errors: list[str] = []
    skills: list[Doc] = []
    agents: list[Doc] = []
    rules: list[Doc] = []

    for skill_md in sorted((AGENTS_DIR / "skills").glob("*/SKILL.md")):
        try:
            doc = parse_frontmatter(skill_md)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        name = str(doc.meta.get("name", ""))
        description = str(doc.meta.get("description", ""))
        if not NAME_RE.match(name):
            errors.append(f"{rel(skill_md)}: invalid name {name!r}")
        if name != skill_md.parent.name:
            errors.append(f"{rel(skill_md)}: name {name!r} must equal folder {skill_md.parent.name!r}")
        if not description or len(description) > 1024:
            errors.append(f"{rel(skill_md)}: description must be 1..1024 characters")
        skills.append(doc)

    names = [str(s.meta.get("name")) for s in skills]
    errors.extend(f"duplicate skill name {n!r}" for n in sorted({n for n in names if names.count(n) > 1}))

    for agent_md in sorted((AGENTS_DIR / "agents").glob("*.md")):
        try:
            doc = parse_frontmatter(agent_md)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        name = str(doc.meta.get("name", ""))
        if name != agent_md.stem or not NAME_RE.match(name):
            errors.append(f"{rel(agent_md)}: name {name!r} must equal file name and be kebab-case")
        if not doc.meta.get("description"):
            errors.append(f"{rel(agent_md)}: missing description")
        tools = doc.meta.get("tools", [])
        if not isinstance(tools, list) or not tools:
            errors.append(f"{rel(agent_md)}: tools must be a non-empty list")
        else:
            errors.extend(f"{rel(agent_md)}: unknown tool {t!r}" for t in tools if t not in CLAUDE_TOOLS)
        for ref in doc.meta.get("agents", []) if isinstance(doc.meta.get("agents"), list) else []:
            if not (agent_md.parent / str(ref)).resolve().exists():
                errors.append(f"{rel(agent_md)}: delegates to missing agent {ref!r}")
        agents.append(doc)

    for rule_md in sorted((AGENTS_DIR / "rules").glob("*.md")):
        try:
            doc = parse_frontmatter(rule_md)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        if doc.meta.get("trigger") not in RULE_TRIGGERS:
            errors.append(f"{rel(rule_md)}: trigger must be one of {sorted(RULE_TRIGGERS)}")
        if not doc.meta.get("description"):
            errors.append(f"{rel(rule_md)}: missing description")
        rules.append(doc)

    return errors, skills, agents, rules


# ---------------------------------------------------------------- generation


def expected_files(skills: list[Doc], agents: list[Doc], rules: list[Doc]) -> dict[Path, bytes]:
    out: dict[Path, bytes] = {}

    for skill in (s for s in skills if s.path.parent.name.startswith(TEAM_PREFIX)):
        name = skill.path.parent.name
        front = f"name: {name}\ndescription: {yaml_str(str(skill.meta['description']))}\n"
        for target in SKILL_TARGETS:
            for src in sorted(p for p in skill.path.parent.rglob("*") if p.is_file()):
                dest = target / name / src.relative_to(skill.path.parent)
                if src == skill.path:
                    out[dest] = with_marker(front, skill.path, skill.body).encode("utf-8")
                else:
                    out[dest] = src.read_bytes()
        workflow = (
            f"---\ndescription: {yaml_str(str(skill.meta['description']))}\n---\n\n"
            f"{MARKER.format(source=rel(skill.path))}\n\n"
            f"Follow the skill `{rel(skill.path)}` step by step. Read it fully before acting.\n"
        )
        out[AGENTS_DIR / "workflows" / f"{name}.md"] = workflow.encode("utf-8")

    for agent in agents:
        name = str(agent.meta["name"])
        description = str(agent.meta["description"])
        tools: list[str] = []
        for tool in agent.meta.get("tools", []):  # type: ignore[union-attr]
            tools.extend(t for t in CLAUDE_TOOLS[str(tool)] if t not in tools)
        claude_front = f"name: {name}\ndescription: {yaml_str(description)}\ntools: {', '.join(tools)}\n"
        out[ROOT / ".claude" / "agents" / f"{name}.md"] = with_marker(claude_front, agent.path, agent.body).encode("utf-8")
        copilot_front = f"name: {name}\ndescription: {yaml_str(description)}\n"
        out[ROOT / ".github" / "agents" / f"{name}.agent.md"] = with_marker(copilot_front, agent.path, agent.body).encode("utf-8")

    for rule in rules:
        apply_to = "**" if rule.meta.get("trigger") == "always_on" else str(rule.meta.get("globs", "**"))
        front = f"description: {yaml_str(str(rule.meta['description']))}\napplyTo: {yaml_str(apply_to)}\n"
        dest = ROOT / ".github" / "instructions" / f"{rule.path.stem}.instructions.md"
        out[dest] = with_marker(front, rule.path, rule.body).encode("utf-8")

    return out


def generated_on_disk() -> set[Path]:
    """Files previously produced by this script (they carry the marker) — used to find orphans."""
    candidates: list[Path] = []
    candidates += list((AGENTS_DIR / "workflows").glob(f"{TEAM_PREFIX}*.md"))
    candidates += list((ROOT / ".claude" / "agents").glob("*.md"))
    candidates += list((ROOT / ".github" / "agents").glob("*.agent.md"))
    candidates += list((ROOT / ".github" / "instructions").glob("*.instructions.md"))
    for target in SKILL_TARGETS:
        candidates += [p for p in target.glob(f"{TEAM_PREFIX}*/**/*") if p.is_file()]
    found = set()
    for path in candidates:
        if path.suffix != ".md" or "GENERATED by tools/agents/sync_agents.py" in path.read_text(encoding="utf-8", errors="ignore"):
            found.add(path)
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="validate and fail on stale adapters, write nothing")
    args = parser.parse_args()

    errors, skills, agents, rules = validate()
    if errors:
        print("Validation errors:")
        print("\n".join(f"  - {e}" for e in errors))
        return 1

    expected = expected_files(skills, agents, rules)
    orphans = sorted(generated_on_disk() - set(expected))
    stale = sorted(p for p, data in expected.items() if not p.exists() or p.read_bytes() != data)

    if args.check:
        for path in stale:
            print(f"stale: {rel(path)}")
        for path in orphans:
            print(f"orphan: {rel(path)} (source removed)")
        if stale or orphans:
            print("Run: python tools/agents/sync_agents.py")
            return 1
        print(f"OK: {len(skills)} skills, {len(agents)} agents, {len(rules)} rules; {len(expected)} generated files up to date")
        return 0

    for path in orphans:
        path.unlink()
        if path.parent.exists() and not any(path.parent.iterdir()):
            shutil.rmtree(path.parent)
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected[path])
    print(f"Generated {len(stale)} file(s), removed {len(orphans)} orphan(s); {len(expected)} adapters total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
